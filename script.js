let currentQuestion = 0;

let scores = {
SUN:0,
TUL:0,
ROS:0,
DAI:0,
CHR:0,
LAV:0
};

let history = [];


const screens =
document.querySelectorAll(".screen");


function showScreen(id){

screens.forEach(screen =>
screen.classList.remove("active")
);

document
.getElementById(id)
.classList.add("active");

window.scrollTo(0,0);

}


document
.getElementById("startBtn")
.addEventListener("click", startQuiz);


function startQuiz(){

currentQuestion = 0;

scores = {
SUN:0,
TUL:0,
ROS:0,
DAI:0,
CHR:0,
LAV:0
};

history = [];

showScreen("quiz");

renderQuestion();

}


function renderQuestion(){

const data =
questions[currentQuestion];

document
.getElementById("questionText")
.textContent =
data.question;


document
.getElementById("progressText")
.textContent =
String(currentQuestion + 1)
.padStart(2,"0")
+
" / "
+
String(questions.length)
.padStart(2,"0");


document
.getElementById("progressBar")
.style.width =
((currentQuestion + 1) /
questions.length * 100)
+
"%";


const answers =
document.getElementById("answers");

answers.innerHTML = "";


data.answers.forEach(
(answer,index)=>{

const button =
document.createElement("button");

button.className =
"answer-btn";

button.innerHTML =
`
<span class="answer-letter">
${String.fromCharCode(65+index)}
</span>
${answer[0]}
`;

button.onclick =
()=> selectAnswer(answer[1]);

answers.appendChild(button);

});

}


function selectAnswer(points){

history.push(points);

Object.keys(points)
.forEach(key => {

scores[key] += points[key];

});


if(
currentQuestion <
questions.length - 1
){

currentQuestion++;

setTimeout(
renderQuestion,
180
);

}

else{

showScreen("analyzing");

setTimeout(
calculateResult,
2200
);

}

}


document
.getElementById("backBtn")
.addEventListener(
"click",
goBack
);


function goBack(){

if(currentQuestion === 0){
return;
}

const previous =
history.pop();

Object.keys(previous)
.forEach(key => {

scores[key] -= previous[key];

});

currentQuestion--;

renderQuestion();

}


function calculateResult(){

let highest =
Math.max(...Object.values(scores));

let winners =
Object.keys(scores)
.filter(
key =>
scores[key] === highest
);


/*
Tie breaker:
If scores are identical,
choose one of the tied results.
Later we can replace this
with secondary scoring.
*/

const winner =
winners[
Math.floor(
Math.random() *
winners.length
)
];

showResult(winner);

}


